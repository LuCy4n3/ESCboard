/* USER CODE BEGIN 0 */
__attribute__((used, noreturn)) void HardFault_Capture(uint32_t *stacked_sp)
{
  __disable_irq();

  g_hardfault_sp = (uint32_t)stacked_sp;
  g_hardfault_cfsr = SCB->CFSR;
  g_hardfault_hfsr = SCB->HFSR;
  g_hardfault_bfar = SCB->BFAR;
  g_hardfault_mmfar = SCB->MMFAR;

  if (stacked_sp != (uint32_t *)0)
  {
    g_hardfault_stacked_lr = stacked_sp[5];
    g_hardfault_stacked_pc = stacked_sp[6];
  }

  while (1)
  {
    HAL_GPIO_TogglePin(GPIOB, GPIO_PIN_7);
    for (volatile uint32_t i = 0; i < 120000UL; i++) { __NOP(); }
  }
}
