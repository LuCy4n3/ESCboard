static int32_t UART_DecodeSigned16BE(uint8_t hi, uint8_t lo)
{
    /* Decode the command explicitly as two's-complement signed 16-bit.
     * Do not rely on an out-of-range uint16_t -> int16_t cast: although that
     * works on the STM32/GCC target, the C conversion is implementation-defined.
     * 0xFFFF therefore becomes -1, 0xF448 becomes -3000, etc. */
    uint32_t raw = ((uint32_t)hi << 8) | (uint32_t)lo;
    return (raw & 0x8000U) ? ((int32_t)raw - 65536) : (int32_t)raw;
}

static uint16_t UART_CommandDmaWriteIndex(void)
{
    uint32_t remaining = DMA1_Channel2->CNDTR;
    if (remaining > UART_CMD_RX_DMA_LEN)
        remaining = UART_CMD_RX_DMA_LEN;
    return (uint16_t)(UART_CMD_RX_DMA_LEN - remaining);
}

static void UART_CommandResetParser(void)
{
    s_uart_cmd_pos = 0U;
    s_uart_cmd_partial_since_ms = 0U;
}

static void UART_CommandFlushBuffered(void)
{
    /* Explicit full flush: normally used only when starting/restarting RX. */
    UART_CommandResetParser();
    s_uart_cmd_rx_read_idx = UART_CommandDmaWriteIndex();
}

static void UART_CommandDmaStart(void)
{
    /* DMA1 clock is already enabled by MX_DMA_Init().  Channel 1 belongs to
     * ADC2, so use otherwise-unused DMA1 Channel 2 / DMAMUX1 Channel 1. */
    CLEAR_BIT(DMA1_Channel2->CCR, DMA_CCR_EN);
    while ((DMA1_Channel2->CCR & DMA_CCR_EN) != 0U) { }

    DMA1->IFCR = DMA_IFCR_CGIF2;

    DMAMUX1_Channel1->CCR =
        ((uint32_t)DMA_REQUEST_USART1_RX << DMAMUX_CxCR_DMAREQ_ID_Pos) &
        DMAMUX_CxCR_DMAREQ_ID_Msk;

    DMA1_Channel2->CPAR  = (uint32_t)&USART1->RDR;
    DMA1_Channel2->CMAR  = (uint32_t)s_uart_cmd_rx_dma;
    DMA1_Channel2->CNDTR = UART_CMD_RX_DMA_LEN;
    DMA1_Channel2->CCR   = DMA_CCR_MINC | DMA_CCR_CIRC | DMA_CCR_PL_1;

    /* Start from a clean UART receive state.  No USART interrupt is enabled. */
    USART1->ICR = USART_ICR_PECF | USART_ICR_FECF |
                  USART_ICR_NECF | USART_ICR_ORECF;
    USART1->RQR = USART_RQR_RXFRQ;

    s_uart_cmd_rx_read_idx = 0U;
    s_uart_cmd_pos = 0U;
    s_uart_cmd_partial_since_ms = 0U;

    SET_BIT(USART1->CR3, USART_CR3_DMAR);
    SET_BIT(DMA1_Channel2->CCR, DMA_CCR_EN);
}

/* Returns 1 only when a complete invalid frame was seen.  The caller then
 * stops processing the current DMA batch because the requested policy is to
 * flush everything, not salvage a later header from the same batch. */
static uint8_t UART_CommandConsumeByte(uint8_t byte)
{
    uint32_t now = HAL_GetTick();

    if (s_uart_cmd_pos == 0U)
    {
        if (byte == UART_CMD_HEADER0)
        {
            s_uart_cmd_frame[0] = byte;
            s_uart_cmd_pos = 1U;
            s_uart_cmd_partial_since_ms = now;
        }
        return 0U;
    }

    if (s_uart_cmd_pos == 1U)
    {
        if (byte == UART_CMD_HEADER1)
        {
            s_uart_cmd_frame[1] = byte;
            s_uart_cmd_pos = 2U;
        }
        else if (byte == UART_CMD_HEADER0)
        {
            /* 15 15 07 ... : the newest 15 can start a fresh header. */
            s_uart_cmd_frame[0] = byte;
            s_uart_cmd_pos = 1U;
            s_uart_cmd_partial_since_ms = now;
        }
        else
        {
            s_uart_cmd_pos = 0U;
            s_uart_cmd_partial_since_ms = 0U;
        }
        return 0U;
    }

    /* Once the complete header has been found, collect exactly CMD + HI + LO.
     * Validation intentionally happens only after all five bytes exist. */
    if (s_uart_cmd_pos >= UART_CMD_FRAME_LEN)
    {
        UART_CommandFlushBuffered();
        return 1U;
    }

    s_uart_cmd_frame[s_uart_cmd_pos++] = byte;
    if (s_uart_cmd_pos < UART_CMD_FRAME_LEN)
        return 0U;

    uint8_t cmd = s_uart_cmd_frame[2];
    int32_t rpm = UART_DecodeSigned16BE(s_uart_cmd_frame[3],
                                       s_uart_cmd_frame[4]);

    if (cmd == UART_CMD_ARM_V13 &&
        s_uart_cmd_frame[3] == 0U && s_uart_cmd_frame[4] == 0U) {
        FastMotor_V13CaptureArm();
        UART_CommandResetParser();
        return 0U;
    }
    if ((cmd != UART_CMD_SET_SPEED) ||
        (rpm < -UART_CMD_MAX_ABS_RPM) ||
        (rpm >  UART_CMD_MAX_ABS_RPM))
    {
        /* Drop only this parser candidate. A later valid frame may already be
         * in the circular DMA buffer behind an EMI-corrupted byte. */
        UART_CommandResetParser();
        return 0U;
    }

    /* The existing motor API is already signed and clamps internally. */
    FastMotor_SetTargetRPM((float)rpm);
    s_uart_cmd_pos = 0U;
    s_uart_cmd_partial_since_ms = 0U;
    return 0U;
}

static void UART_CommandService(void)
{
    /* Hardware UART errors invalidate all bytes collected so far.  Handle them
     * in main context; no USART error interrupt is enabled. */
    uint32_t isr = USART1->ISR;
    if ((isr & (USART_ISR_PE | USART_ISR_FE | USART_ISR_NE | USART_ISR_ORE)) != 0U)
    {
        /* Motor-edge EMI can cause an occasional FE/NE/ORE. Keep RX DMA alive
         * and preserve later buffered commands; only abandon the partial frame. */
        USART1->ICR = USART_ICR_PECF | USART_ICR_FECF |
                      USART_ICR_NECF | USART_ICR_ORECF;
        UART_CommandResetParser();
    }

    /* A valid 5-byte frame takes ~0.11 ms at 460800 baud.  Keep a much longer
     * timeout because the main loop can be held inside telemetry TX. */
    if ((s_uart_cmd_pos != 0U) &&
        (s_uart_cmd_partial_since_ms != 0U) &&
        ((uint32_t)(HAL_GetTick() - s_uart_cmd_partial_since_ms) >
         UART_CMD_PARTIAL_TIMEOUT_MS))
    {
        UART_CommandResetParser();
    }

    uint16_t write_idx = UART_CommandDmaWriteIndex();

    while (s_uart_cmd_rx_read_idx != write_idx)
    {
        uint8_t byte = s_uart_cmd_rx_dma[s_uart_cmd_rx_read_idx];
        s_uart_cmd_rx_read_idx++;
        if (s_uart_cmd_rx_read_idx >= UART_CMD_RX_DMA_LEN)
            s_uart_cmd_rx_read_idx = 0U;

        (void)UART_CommandConsumeByte(byte);

        /* Refresh because DMA can continue writing while we parse. */
        write_idx = UART_CommandDmaWriteIndex();
    }
}
